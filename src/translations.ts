/**
 * Safe translation lookup helper.
 * If key is missing in target language, it automatically falls back to English,
 * and if still missing, to the provided fallback or the key itself.
 */
export function t(lang: LanguageCode, key: string, fallback?: string): string {
  const dict = translations[lang] || translations.rw || translations.en;
  if (dict && dict[key]) {
    return dict[key];
  }
  // Fallback to English
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  // Fallback to Kinyarwanda
  if (translations.rw && translations.rw[key]) {
    return translations.rw[key];
  }
  return fallback || key;
}

/**
 * Convenient hook-like or functional getter for a specific language
 */
export function getTranslations(lang: LanguageCode) {
  const current = translations[lang] || translations.rw;
  const enFallback = translations.en || {};

  return new Proxy(current, {
    get(target, prop: string) {
      if (prop in target) {
        return target[prop];
      }
      if (prop in enFallback) {
        return enFallback[prop];
      }
      return prop;
    }
  });
}
